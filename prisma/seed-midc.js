async function seedMidcData() {
  console.log('🏭 Seeding authentic Nashik MIDC Business Directory records...');

  let count = 0;
  for (const b of MIDC_BUSINESSES) {
    const existing = await prisma.midcBusiness.findFirst({
      where: {
        companyName: b.companyName,
        midcArea: b.midcArea,
      },
    });

    if (!existing) {
      await prisma.midcBusiness.create({
        data: b,
      });
      count++;
      console.log(`  ✓ Added: ${b.companyName} [${b.midcArea} - ${b.businessType}]`);
    } else {
      await prisma.midcBusiness.update({
        where: { id: existing.id },
        data: b,
      });
      console.log(`  ↺ Updated: ${b.companyName} [${b.midcArea}]`);
    }
  }

  console.log(`\n🎉 Seeded ${count} new MIDC business directory records successfully! Total: ${MIDC_BUSINESSES.length}`);
}

seedMidcData()
  .catch((err) => {
    console.error('Error seeding MIDC data:', err);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
